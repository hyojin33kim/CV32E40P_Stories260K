#!/usr/bin/env python3
"""Generate opta/run_opta.c: llama2.c run.c with the Option A numerics (S3, 11-15), the host
model of firmware_gen.c -DOPTA. Every replaced snippet must occur exactly once in run.c.
  - attention score: no '/= sqrtf(head_size)' (folded into OPTA_K)
  - softmax(att) -> sum = softmax2(att) (opta/softmax2.h: exp2q, 4-way sum, no normalization)
  - after the AV loop: xb[i] /= sum for the head's 8 outputs (deferred normalization)
  - SiLU: 1/(1 + expf(-x)) -> 1/(1 + exp2q(x * -log2(e)))
The sampler's softmax (temperature sampling) is untouched; generation here is greedy."""
from pathlib import Path

W = Path(__file__).resolve().parent.parent
t = (W / 'run.c').read_text()
REPL = [
    ('#include <math.h>\n', '#include <math.h>\n#include "softmax2.h"\n'),
    ('                score /= sqrtf(head_size);\n', '                // Option A: /sqrt(head_size) folded into OPTA_K\n'),
    ('            softmax(att, pos + 1);\n', '            float sum = softmax2(att, pos + 1);   // Option A: unnormalized\n'),
    ('''                for (int i = 0; i < head_size; i++) {
                    xb[i] += a * v[i];
                }
            }
''', '''                for (int i = 0; i < head_size; i++) {
                    xb[i] += a * v[i];
                }
            }
            // Option A: deferred normalization of the head's outputs
            for (int i = 0; i < head_size; i++) {
                xb[i] /= sum;
            }
'''),
    ('            val *= (1.0f / (1.0f + expf(-val)));\n',
     '            val *= (1.0f / (1.0f + exp2q(val * OPTA_NLOG2E)));   // Option A\n'),
]
for a, b in REPL:
    assert t.count(a) == 1, a
    t = t.replace(a, b)
hdr = '// GENERATED by opta/make_run_opta.py from run.c (llama2.c) - do not edit\n'
(W / 'opta' / 'run_opta.c').write_text(hdr + t)
print('opta/run_opta.c written')
