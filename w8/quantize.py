#!/usr/bin/env python3
"""I1: offline int8 quantization of the Stories260K weight matrices (per-row scale, numpy float32) and the
W8 weight image layout.

  w8/quantize.py layout            -> writes w8/w8_layout.h (addresses used by the firmware)
  w8/quantize.py pack <image.bin>  -> rewrites the weight region 0x20000..0xFD400 of an image built by image.py:
                                      int8 matrices (rows padded to 16 B) then the fp32 row scales; the old fp32
                                      matrices there are zeroed. Embedding (0x0), RMS weights (0xFD400..) untouched.
  w8/quantize.py dump <out.bin>    -> raw dump (wq int8 per matrix, then scales) for the C cross-check

Quantization (identical to w8/make_run_w8.py): m = max|row|, s = m / 127 (fp32), q = clamp(rint(w / s), +-127),
q = 0 and s = 0 for an all-zero row. Matrices (llama2.c order and shapes, d rows x n columns, per layer):
  wq 64x64, wk 32x64, wv 32x64, wo 64x64, w1 172x64, w2 64x172, w3 172x64; classifier (= embedding table) 512x64."""
import struct, sys
from pathlib import Path
import numpy as np

W = Path(__file__).resolve().parent.parent
L, DIM, HID, KV, V = 5, 64, 172, 32, 512
# name: (checkpoint word offset, layers, d rows, n columns); offsets as in image.py
MATS = {'wq': (0x20000, L, DIM, DIM), 'wk': (0x34000, L, KV, DIM), 'wv': (0x3e000, L, KV, DIM),
        'wo': (0x48000, L, DIM, DIM), 'w1': (0x5c000, L, HID, DIM), 'w2': (0x91c00, L, DIM, HID),
        'w3': (0xc7800, L, HID, DIM), 'cls': (0x0, 1, V, DIM)}
ORDER = ['wq', 'wk', 'wv', 'wo', 'w1', 'w2', 'w3', 'cls']
BASE = 0x20000            # first byte of the int8 area (the fp32 matrices start here in the fp32 image)
LIMIT = 0xfd400           # RMS weights start here

def stride(n): return (n + 15) // 16 * 16

def layout():
    """name -> dict(addr, sc, stride, layers, d, n) with byte addresses of the int8 matrices and the scales"""
    out, a = {}, BASE
    for k in ORDER:
        _, lay, d, n = MATS[k]
        out[k] = dict(addr=a, stride=stride(n), layers=lay, d=d, n=n); a += lay * d * stride(n)
    a = (a + 15) // 16 * 16
    for k in ORDER:
        _, lay, d, n = MATS[k]
        out[k]['sc'] = a; a += lay * d * 4
    assert a <= LIMIT, hex(a)
    out['_end'] = a
    return out

def read_mats():
    b = (W / 'stories260K.bin').read_bytes()
    assert struct.unpack_from('7i', b) == (64, 172, 5, 8, 4, 512, 512)
    f = np.frombuffer(b, dtype='<f4', offset=28)
    # checkpoint order (image.py): emb 32768 words, rms_att 320, wq, wk, wv, wo, rms_ffn 320, w1, w2, w3, rms_final 64
    o = {'cls': f[0:32768]}
    p = 32768 + 320
    for k, cnt in (('wq', 20480), ('wk', 10240), ('wv', 10240), ('wo', 20480)):
        o[k] = f[p:p + cnt]; p += cnt
    p += 320
    for k in ('w1', 'w2', 'w3'):
        o[k] = f[p:p + 55040]; p += 55040
    return {k: o[k].reshape(MATS[k][1], MATS[k][2], MATS[k][3]) for k in ORDER}

def quantize(M):
    """M (d, n) float32 -> q (d, n) int8, s (d,) float32"""
    M = M.astype(np.float32)
    m = np.abs(M).max(axis=1)
    s = (m / np.float32(127.0)).astype(np.float32)
    safe = np.where(s == 0, np.float32(1.0), s)
    q = np.rint(M / safe[:, None]).astype(np.float32)
    q = np.clip(q, -127, 127)
    q[s == 0] = 0
    return q.astype(np.int8), s

def quantized():
    mats = read_mats()
    out = {}
    for k in ORDER:
        qs, ss = [], []
        for l in range(MATS[k][1]):
            q, s = quantize(mats[k][l]); qs.append(q); ss.append(s)
        out[k] = (np.stack(qs), np.stack(ss))
    return out

def main():
    cmd = sys.argv[1]
    lay = layout()
    if cmd == 'layout':
        with open(W / 'w8' / 'w8_layout.h', 'w') as h:
            h.write('// generated by w8/quantize.py layout: W8 weight image (int8 matrices, fp32 row scales)\n')
            for k in ORDER:
                d = lay[k]
                h.write(f'#define W8_{k.upper()}_Q  0x{d["addr"]:x}u   /* int8, layer stride {d["d"] * d["stride"]} B, row stride {d["stride"]} B, n={d["n"]}, d={d["d"]} */\n')
                h.write(f'#define W8_{k.upper()}_S  0x{d["sc"]:x}u   /* fp32 row scales, layer stride {d["d"] * 4} B */\n')
                h.write(f'#define W8_{k.upper()}_STRIDE {d["stride"]}\n')
            h.write(f'#define W8_END 0x{lay["_end"]:x}u\n')
        print('w8/w8_layout.h written, int8 area end 0x%x (%d KiB incl. scales)' % (lay['_end'], (lay['_end'] - BASE) // 1024))
    elif cmd == 'pack':
        img = Path(sys.argv[2]); m = bytearray(img.read_bytes())
        m[BASE:LIMIT] = bytes(LIMIT - BASE)
        qz = quantized()
        for k in ORDER:
            d = lay[k]; q, s = qz[k]
            for l in range(d['layers']):
                for i in range(d['d']):
                    a = d['addr'] + (l * d['d'] + i) * d['stride']
                    m[a:a + d['n']] = q[l, i].tobytes()
            sa = d['sc']; m[sa:sa + d['layers'] * d['d'] * 4] = s.astype('<f4').tobytes()
        img.write_bytes(m); print('packed', img)
    elif cmd == 'dump':
        qz = quantized()
        with open(sys.argv[2], 'wb') as o:
            for k in ORDER:
                o.write(qz[k][0].tobytes()); o.write(qz[k][1].astype('<f4').tobytes())
        print('dumped', sys.argv[2])

if __name__ == '__main__':
    main()
